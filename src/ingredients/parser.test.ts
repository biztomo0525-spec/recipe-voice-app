for (const [kind, input, expected] of CASES) {
  test(`[${kind}] ${JSON.stringify(input)} → ${JSON.stringify(expected)}`, () => {
    assert.equal(parseMaterial(input), expected);
  });
}

// --- 不変条件 ---
test('結果に装飾記号が先頭・末尾に残らない', () => {
  for (const [, input] of CASES) {
    const out = parseMaterial(input);
    if (out === null) continue;
    assert.ok(/^[\p{L}\p{N}]/u.test(out), `先頭が記号: ${JSON.stringify(out)}`);
    assert.ok(/[\p{L}\p{N}]$/u.test(out), `末尾が記号: ${JSON.stringify(out)}`);
  }
});

test('結果に括弧が残らない', () => {
  for (const [, input] of CASES) {
    const out = parseMaterial(input);
    if (out === null) continue;
    assert.ok(!/[(（【\[〈《]/u.test(out), `括弧が残存: ${JSON.stringify(out)}`);
  }
});
